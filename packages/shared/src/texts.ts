const chars = (value: string) => Array.from(value.normalize('NFC'));
const HAS_MN_SPECIFIC = /[ӨөҮү]/u;

/** Small deterministic PRNG (mulberry32) so a seed reproduces a passage exactly. */
export function seededRandom(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

type Window = { story: Story; start: number; count: number; text: string };
const windowCache = new Map<string, Window[]>();

/** Every run of consecutive sentences whose joined length fits the size budget.
 * Enumerated once per budget; the pool is what makes passages varied yet coherent. */
export function passageWindows(min = RACE_TEXT_MIN, max = RACE_TEXT_MAX): Window[] {
  const key = min + ':' + max;
  const cached = windowCache.get(key);
  if (cached) return cached;
  const result: Window[] = [];
  for (const story of STORIES) {
    for (let start = 0; start < story.sentences.length; start++) {
      for (let count = 1; start + count <= story.sentences.length; count++) {
        const text = story.sentences.slice(start, start + count).join(' ');
        const length = chars(text).length;
        if (length > max) break;
        if (length >= min && HAS_MN_SPECIFIC.test(text)) result.push({ story, start, count, text });
      }
    }
  }
  windowCache.set(key, result);
  return result;
}

export type GenerateOptions = {
  mode?: TextMode;
  /** Deterministic selection; omit for a random passage. */
  seed?: number;
  /** Text to avoid (for example the previous race) so a rematch gets fresh words. */
  exclude?: string;
  /** More than one recent passage to avoid in a public matchmaking rotation. */
  excludes?: readonly string[];
  min?: number;
  max?: number;
};

function storyPassage(rng: () => number, min: number, max: number, exclude?: string,
  excludes: readonly string[] = []): RacePassage {
  let pool = passageWindows(min, max);
  if (!pool.length) pool = passageWindows(RACE_TEXT_MIN, RACE_TEXT_MAX);
  const blockedTexts = new Set([...excludes, ...(exclude ? [exclude] : [])]);
  if (blockedTexts.size) {
    const blockedStories = new Set(pool.filter(window => blockedTexts.has(window.text)).map(window => window.story.id));
    const fresh = pool.filter(window => !blockedTexts.has(window.text) && !blockedStories.has(window.story.id));
    const other = fresh.length ? fresh : pool.filter(window => !blockedTexts.has(window.text));
    if (other.length) pool = other;
  }
  const pick = pool[Math.min(pool.length - 1, Math.floor(rng() * pool.length))];
  const from = pick.start + 1;
  const to = pick.start + pick.count;
  return {
    id: 'mn-' + pick.story.id + '-' + from + '-' + pick.count, language: 'mn', text: pick.text,
    title: pick.story.title, part: (from === to ? String(from) : from + '–' + to) + '/' + pick.story.sentences.length,
    mode: 'story', words: pick.text.split(' ').length
  };
}

function wordsPassage(rng: () => number, min: number, max: number, exclude?: string): RacePassage {
  for (let attempt = 0; attempt < 8; attempt++) {
    const picked: string[] = [];
    let length = 0;
    while (true) {
      const word = WORDS[Math.min(WORDS.length - 1, Math.floor(rng() * WORDS.length))];
      const next = length + chars(word).length + (picked.length ? 1 : 0);
      if (next > max) { if (length >= min) break; continue; }
      if (picked[picked.length - 1] === word) continue;
      picked.push(word);
      length = next;
    }
    const text = picked.join(' ');
    if (text !== exclude && HAS_MN_SPECIFIC.test(text))
      return { id: 'mn-words-' + picked.length + '-' + Math.floor(rng() * 1e9).toString(36), language: 'mn', text,
        title: 'Санамсаргүй үгс', part: picked.length + ' үг', mode: 'words', words: picked.length };
  }
  return storyPassage(rng, RACE_TEXT_MIN, RACE_TEXT_MAX, exclude);
}

/**
 * Produce one race text. Story mode (default) returns consecutive sentences of a
 * single original story; words mode returns Monkeytype-style random common words.
 * Every result contains Ө or Ү and stays within the character budget.
 */
export function generatePassage(options: GenerateOptions = {}): RacePassage {
  const mode = options.mode === 'words' ? 'words' : 'story';
  const rng = options.seed === undefined ? Math.random : seededRandom(options.seed);
  if (mode === 'words') return wordsPassage(rng, options.min ?? WORDS_TEXT_MIN, options.max ?? WORDS_TEXT_MAX, options.exclude);
  return storyPassage(rng, options.min ?? RACE_TEXT_MIN, options.max ?? RACE_TEXT_MAX,
    options.exclude, options.excludes);
}

/** Distinct story passages the generator can currently produce. */
export function passageCount(min = RACE_TEXT_MIN, max = RACE_TEXT_MAX): number {
  return passageWindows(min, max).length;
}
